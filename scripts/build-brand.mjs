import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const type = JSON.parse(fs.readFileSync(path.join(root, "assets/brief/type-outlines.json"), "utf8"));
const manifest = JSON.parse(fs.readFileSync(path.join(root, "newsletter/issues.json"), "utf8"));
const palettes = {
  light: { paper: "#f5f0e7", ink: "#233b32", accent: "#ad402d", line: "#b7b8a7", sheet: "#e8e8d9" },
  dark: { paper: "#172b26", ink: "#f0e9da", accent: "#f0a184", line: "#607367", sheet: "#233c32" },
};
const xml = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll('"', "&quot;");
const n = (value) => Number(value.toFixed(4));
const paths = (run, x, baseline, width, fill) => {
  const scale = width / run.width;
  return '<g fill="' + fill + '" transform="translate(' + x + " " + baseline + ") scale("
    + n(scale) + " " + n(-scale) + ')">'
    + run.glyphs.map((glyph) => '<path transform="translate(' + glyph.x + " " + glyph.y
      + ')" d="' + glyph.d + '"/>').join("") + "</g>";
};
const digits = (text) => {
  let width = 0;
  const glyphs = [];
  for (const char of text) {
    const run = type.digits[char];
    for (const glyph of run.glyphs) glyphs.push({ ...glyph, x: glyph.x + width });
    width += run.width;
  }
  return { width, glyphs };
};
const text = (x, y, size, fill, content, extra = "") =>
  '<text x="' + x + '" y="' + y + '" font-family="Trebuchet MS, sans-serif" font-size="'
  + size + '" fill="' + fill + '" ' + extra + ">" + xml(content) + "</text>";
const line = (x1, y1, x2, y2, color, width = 1) =>
  '<path d="M' + x1 + " " + y1 + "H" + x2 + (y1 === y2 ? "" : "V" + y2)
  + '" fill="none" stroke="' + color + '" stroke-width="' + width + '"/>';
const wrap = (width, height, title, description, body) =>
  '<svg xmlns="http://www.w3.org/2000/svg" width="' + width + '" height="' + height
  + '" viewBox="0 0 ' + width + " " + height + '" role="img" aria-labelledby="title desc">\n'
  + "<!-- Generated by scripts/build-brand.mjs; Newsreader outlines: see OFL-Newsreader.txt. -->\n"
  + '<title id="title">' + xml(title) + '</title><desc id="desc">' + xml(description) + "</desc>\n"
  + body + "\n</svg>\n";

function masthead(p, mobile) {
  const width = mobile ? 600 : 1200;
  const height = mobile ? 108 : 144;
  const margin = mobile ? 26 : 48;
  const top = mobile ? 24 : 26;
  let body = '<path fill="' + p.paper + '" d="M0 0H' + width + "V" + height + 'H0Z"/>';
  body += text(margin, top, mobile ? 17 : 17, p.accent, "THE PRACTITIONER'S EDITION", 'letter-spacing="2" font-weight="700"');
  if (!mobile) {
    body += text(1152, 26, 17, p.ink, "EST. 2026 / SEOUL", 'text-anchor="end" letter-spacing="2"');
  }
  body += paths(type.wordmark, margin - 2, mobile ? 74 : 102, mobile ? 548 : 880, p.ink);
  body += line(margin, mobile ? 88 : 118, width - margin, mobile ? 88 : 118, p.ink, 2);
  if (!mobile) body += text(1152, 94, 17, p.accent, "SKILLS / MCP / HARNESS", 'text-anchor="end" letter-spacing="1"');
  return wrap(width, height, "Agent Stack Brief", "An editorial masthead in paper, ink, and vermilion. Skills, MCP, and Harness.", body);
}

function cover(issue, p, mobile) {
  if (issue.cover.layout === "index") {
    const width = mobile ? 600 : 1200;
    const height = mobile ? 172 : 148;
    const margin = mobile ? 26 : 48;
    let body = '<path fill="' + p.paper + '" d="M0 0H' + width + 'V' + height + 'H0Z"/>';
    body += text(margin, 34, 19, p.accent, "FIELD NOTE / " + issue.id, 'letter-spacing="2" font-weight="700"');
    body += text(width - margin, 34, 18, p.ink, issue.date.replaceAll("-", "."), 'text-anchor="end"');
    body += line(margin, 50, width - margin, 50, p.ink);
    for (const [i, label] of issue.cover.labels.entries()) {
      body += text(mobile ? margin : margin + i * 376, mobile ? 82 + i * 34 : 102,
        mobile ? 24 : 28, p.ink, "0" + (i + 1) + " / " + label, 'letter-spacing="2"');
    }
    return wrap(width, height, "Field note " + issue.id,
      "Issue " + issue.id + ": " + issue.cover.labels.join(", ") + ". Editorial contents, not interactive controls.", body);
  }
  const width = mobile ? 600 : 1200;
  const height = mobile ? 252 : 300;
  let body = '<path fill="' + p.paper + '" d="M0 0H' + width + "V" + height + 'H0Z"/>';
  body += '<path d="M' + (mobile ? 210 : 344) + " 26V" + (height - 26)
    + '" stroke="' + p.line + '"/>';
  body += text(mobile ? 24 : 48, mobile ? 44 : 46, mobile ? 25 : 22, p.accent,
    "FIELD NOTE", 'letter-spacing="3" font-weight="700"');
  body += paths(digits(issue.id), mobile ? 20 : 38, mobile ? 201 : 244,
    mobile ? 166 : 270, p.accent);
  if (!mobile) body += text(48, 277, 18, p.ink, issue.date.replaceAll("-", "."), 'letter-spacing="2"');
  const x = mobile ? 234 : 392;
  const boxWidth = mobile ? 340 : 760;
  const firstY = mobile ? 27 : 30;
  const step = mobile ? 69 : 82;
  for (const [i, label] of issue.cover.labels.entries()) {
    const y = firstY + i * step;
    const height = mobile ? 60 : 68;
    body += '<path fill="' + (i === 1 ? p.sheet : p.paper) + '" stroke="' + p.ink
      + '" d="M' + x + " " + y + "h" + boxWidth + "v" + height + "h-" + boxWidth + 'z"/>';
    body += text(x + (mobile ? 20 : 28), y + (mobile ? 39 : 44), mobile ? 29 : 32,
      p.ink, label, 'letter-spacing="3" font-weight="700"');
    const end = x + boxWidth - (mobile ? 24 : 34);
    body += '<path d="M' + (end - 24) + " " + (y + height / 2) + "h24m0-16v32"
      + '" stroke="' + p.accent + '" stroke-width="3" fill="none"/>';
  }
  return wrap(width, height, "Field note " + issue.id,
    "Issue " + issue.id + ": " + issue.cover.labels.join(", ") + ". Editorial illustration, not test results.", body);
}

const files = [];
for (const [theme, palette] of Object.entries(palettes)) {
  for (const mobile of [false, true]) {
    const variant = (mobile ? "-mobile" : "") + "-" + theme + ".svg";
    files.push(["assets/brief/masthead" + variant, masthead(palette, mobile)]);
    for (const issue of manifest.issues.filter((issue) => issue.cover)) {
      files.push(["assets/brief/issue-" + issue.id + variant, cover(issue, palette, mobile)]);
    }
  }
}
if (process.argv.includes("--check")) {
  for (const [file, source] of files) {
    if (!fs.existsSync(path.join(root, file)) || fs.readFileSync(path.join(root, file), "utf8") !== source) {
      throw new Error("Brand asset missing or stale: " + file + ". Regenerate with --patch.");
    }
  }
  console.log("PASS: " + files.length + " deterministic brand assets; desktop/mobile and light/dark variants.");
} else if (process.argv.includes("--patch")) {
  const patches = [];
  for (const [file, source] of files) {
    const exists = fs.existsSync(path.join(root, file));
    const old = exists ? fs.readFileSync(path.join(root, file), "utf8") : "";
    if (old === source) continue;
    patches.push((exists ? "*** Update File: " : "*** Add File: ") + path.join(root, file)
      + (exists ? "\n@@\n" + old.trimEnd().split("\n").map((line) => "-" + line).join("\n") : "")
      + "\n" + source.trimEnd().split("\n").map((line) => "+" + line).join("\n"));
  }
  if (patches.length) process.stdout.write("*** Begin Patch\n" + patches.join("\n") + "\n*** End Patch\n");
} else {
  console.log("Use --check to validate assets or --patch to print a reviewable apply_patch patch. No dependencies or network required.");
}
